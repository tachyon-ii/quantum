"""atlas/atlas.py — the slices, from the mass table alone. No model, no fitted number, no mechanism (SPEC v6 P17).
One source: AME2020 measured binding energies via models/kernel/data.py (estimated '#' entries excluded).
Writes review/2026-11-18/ATLAS-slices.md (R4': report written by code). Grace (Claude Fable 5.2), 19 Nov 2026."""
import sys,os,numpy as np
HERE=os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0,os.path.join(HERE,'..','kernel'))
import data as D
B=D.BE; Q0=D.MN-D.MP-D.ME; BA=D.be(2,2)
SYM="n H He Li Be B C N O F Ne Na Mg Al Si P S Cl Ar K Ca Sc Ti V Cr Mn Fe Co Ni Cu Zn Ga Ge As Se Br Kr Rb Sr Y Zr Nb Mo Tc Ru Rh Pd Ag Cd In Sn Sb Te I Xe Cs Ba La Ce Pr Nd Pm Sm Eu Gd Tb Dy Ho Er Tm Yb Lu Hf Ta W Re Os Ir Pt Au Hg Tl Pb Bi Po At Rn Fr Ra Ac Th Pa U Np Pu Am Cm Bk Cf Es Fm Md No Lr Rf Db Sg Bh Hs Mt Ds Rg Cn Nh Fl Mc Lv Ts Og".split()
nm=lambda Z,N:f"{SYM[Z]}-{Z+N}"
g=lambda Z,N:B.get((Z,N))
L=[]; P=L.append
P("# Atlas of slices — what the mass table says, with no model\n")
P("*Generated by `models/atlas/atlas.py` from AME2020 measured binding energies (%d nuclides). No fitted number and no mechanism anywhere in this file. Every table is a slice the answer must pass (SPEC v6 §2). Half-lives are not used: the half-life table is not in `data/`.*\n"%len(B))
# ---------- 1. odd-even
P("## 1. Even beats odd\n")
P("For each nuclide with a measured neighbour on both sides: is it more bound (even count) or less bound (odd count) than the mean of its two neighbours? `gap` > 0 means the rule holds.\n")
def oe(kind):
    out=[]
    for (Z,N),b in B.items():
        a,c=(g(Z,N-1),g(Z,N+1)) if kind=='n' else (g(Z-1,N),g(Z+1,N))
        if a is None or c is None: continue
        d=0.5*(a+c)-b; par=N if kind=='n' else Z
        out.append((Z,N,d if par%2 else -d))
    return out
P("| count | nuclides | rule holds | exceptions | mean gap (MeV) |"); P("|---|---|---|---|---|")
EXC={}
for k,lab in (('n','neutron number'),('p','proton number')):
    o=oe(k); ex=[(Z,N,s) for Z,N,s in o if s<=0]; EXC[k]=ex
    P(f"| {lab} | {len(o)} | {len(o)-len(ex)} | {len(ex)} | {np.mean([s for *_,s in o]):.2f} |")
P("\n**Every exception:**\n"); P("| nuclide | Z | N | count tested | gap (MeV) | odd-odd with N = Z? |"); P("|---|---|---|---|---|---|")
for k in ('n','p'):
    for Z,N,s in sorted(EXC[k]): P(f"| {nm(Z,N)} | {Z} | {N} | {'neutron' if k=='n' else 'proton'} | {s:+.3f} | {'yes' if (Z==N and Z%2) else 'NO'} |")
P("\n**Size of the gap against mass number** (mean over nuclides in the band):\n"); P("| A | neutron gap | proton gap | 12/√A for comparison |"); P("|---|---|---|---|")
on,op=oe('n'),oe('p')
for lo,hi in ((4,16),(16,40),(40,80),(80,140),(140,200),(200,300)):
    f=lambda o:np.mean([s for Z,N,s in o if lo<=Z+N<hi])
    P(f"| {lo}–{hi} | {f(on):.2f} | {f(op):.2f} | {12/np.sqrt((lo+hi)/2):.2f} |")
# ---------- 2. N=Z odd-odd partner
P("\n## 2. The cross-kind partner: odd-odd nuclei with N = Z against their odd-odd neighbours\n")
P("Gap as in §1 (neutron count). Rule failing = the odd proton and odd neutron behave as a pair.\n"); P("| Z = N | nuclide | gap at N = Z | gap one step off (N = Z+2, same Z) |"); P("|---|---|---|---|")
dn={(Z,N):s for Z,N,s in on}
for Z in range(1,40,2):
    if (Z,Z) in dn: P(f"| {Z} | {nm(Z,Z)} | {dn[(Z,Z)]:+.3f} | {dn.get((Z,Z+2),float('nan')):+.3f} |")
# ---------- 3. alpha gains
P("\n## 3. The gain from adding one alpha\n")
P("Gain = BE(Z+2, N+2) − BE(Z, N) − BE(⁴He). Along N = Z (the alpha ladder), then the same quantity for every even-even nuclide, averaged by how far the *product* sits past a closed number.\n")
P("| step | gain (MeV) |"); P("|---|---|")
for k in range(1,16):
    a,b=g(2*k,2*k),g(2*k+2,2*k+2)
    if a and b: P(f"| {nm(2*k,2*k)} → {nm(2*k+2,2*k+2)} | {b-a-BA:.2f} |")
MAG=[2,8,20,28,50,82,126]
P("\n**All even-even nuclides: mean alpha gain by where the product's neutron number sits relative to a closed number** (products with 8 ≤ Z):\n")
P("| product N relative to closed number | mean gain (MeV) | nuclides |"); P("|---|---|---|")
rel={}
for (Z,N),b in B.items():
    if Z%2 or N%2 or Z<6: continue
    c=g(Z+2,N+2)
    if c is None: continue
    for m in MAG[1:]:
        d=(N+2)-m
        if -4<=d<=6: rel.setdefault(d,[]).append(c-b-BA)
for d in sorted(rel): P(f"| {d:+d} | {np.mean(rel[d]):.2f} | {len(rel[d])} |")
P("\n**The same, by the product's proton number:**\n"); P("| product Z relative to closed number | mean gain (MeV) | nuclides |"); P("|---|---|---|")
rel={}
for (Z,N),b in B.items():
    if Z%2 or N%2 or Z<6: continue
    c=g(Z+2,N+2)
    if c is None: continue
    for m in MAG[1:]:
        d=(Z+2)-m
        if -4<=d<=6: rel.setdefault(d,[]).append(c-b-BA)
for d in sorted(rel): P(f"| {d:+d} | {np.mean(rel[d]):.2f} | {len(rel[d])} |")
# ---------- 4. extras on closed cores
P("\n## 4. Extras on a closed core\n")
P("For each core: the separation energy of the k-th added neutron (how strongly the k-th extra is held), and the energy released if the resulting nuclide beta-decays (≤ 0: it cannot). `—` = not measured.\n")
CORES=[(2,2),(8,8),(20,20),(20,28),(28,28),(50,82),(82,126)]
for Z,N0 in CORES:
    P(f"\n**Core {nm(Z,N0)}, adding neutrons**\n"); P("| extras k | nuclide | held by (MeV) | beta-minus energy (MeV) | electron-capture energy (MeV) |"); P("|---|---|---|---|---|")
    for k in range(0,9):
        N=N0+k; b=g(Z,N)
        if b is None: P(f"| {k} | {nm(Z,N)} | — | — | — |"); continue
        sn=b-g(Z,N-1) if g(Z,N-1) else None; qb=g(Z+1,N-1)-b+Q0 if g(Z+1,N-1) else None; qe=g(Z-1,N+1)-b-Q0 if g(Z-1,N+1) else None
        f=lambda x:'—' if x is None else f'{x:+.2f}'
        P(f"| {k} | {nm(Z,N)} | {f(sn) if k else '(core)'} | {f(qb)} | {f(qe)} |")
for Z0,N in ((2,2),(8,8),(20,20),(28,28),(50,82),(82,126)):
    P(f"\n**Core {nm(Z0,N)}, adding protons**\n"); P("| extras k | nuclide | held by (MeV) | beta-minus energy (MeV) | electron-capture energy (MeV) |"); P("|---|---|---|---|---|")
    for k in range(0,7):
        Z=Z0+k; b=g(Z,N)
        if b is None: P(f"| {k} | {nm(Z,N)} | — | — | — |"); continue
        sp=b-g(Z-1,N) if g(Z-1,N) else None; qb=g(Z+1,N-1)-b+Q0 if g(Z+1,N-1) else None; qe=g(Z-1,N+1)-b-Q0 if g(Z-1,N+1) else None
        f=lambda x:'—' if x is None else f'{x:+.2f}'
        P(f"| {k} | {nm(Z,N)} | {f(sp) if k else '(core)'} | {f(qb)} | {f(qe)} |")
# ---------- 5. bell per element
P("\n## 5. The bell for every element\n")
P("For each even Z: the neutron numbers at which the nuclide can neither beta-minus decay nor capture an electron (the floor of the bell), and N − Z at its centre. A nuclide is listed only if both beta neighbours are measured.\n")
P("| element | Z | beta-stable N | count | centre N − Z |"); P("|---|---|---|---|---|")
def bstable(Z,N):
    b=g(Z,N)
    if b is None: return False
    u,d=g(Z+1,N-1),g(Z-1,N+1)
    if Z+N>16 and (u is None or d is None): return False     # unknown neighbour: not asserted stable
    return not ((u is not None and u-b+Q0>0) or (d is not None and d-b-Q0>0))
for Z in range(2,84,2):
    ns=[N for N in range(1,140) if bstable(Z,N)]
    if ns: P(f"| {SYM[Z]} | {Z} | {', '.join(map(str,ns))} | {len(ns)} | {np.mean(ns)-Z:+.1f} |")
P("\n**Odd Z, for comparison:**\n"); P("| element | Z | beta-stable N | count |"); P("|---|---|---|---|")
for Z in range(1,84,2):
    ns=[N for N in range(0,140) if bstable(Z,N)]
    P(f"| {SYM[Z]} | {Z} | {', '.join(map(str,ns)) if ns else 'none'} | {len(ns)} |")
# ---------- 6. exits
P("\n## 6. Exits\n")
P("For every measured nuclide whose neighbours are also measured (`unknown` otherwise): which ways out are open on energy alone — beta-minus, electron capture, alpha, one neutron, one proton. A nuclide with no exit open cannot decay by any of these. One with an exit open that is nonetheless found in nature is holding a lock against an available way out; those are slices of the second kind (SPEC v6 P14).\n")
cnt={}; noexit=[]; alpha_only=[]
for (Z,N),b in B.items():
    ex=[]
    u,d=g(Z+1,N-1),g(Z-1,N+1)
    if Z+N>16 and (u is None or d is None or g(Z-2,N-2) is None): cnt['unknown']=cnt.get('unknown',0)+1; continue
    if u is not None and u-b+Q0>0: ex.append('b-')
    if d is not None and d-b-Q0>0: ex.append('ec')
    a=g(Z-2,N-2)
    if a is not None and a+BA-b>0: ex.append('a')
    if g(Z,N-1) is not None and b-g(Z,N-1)<0: ex.append('n')
    if g(Z-1,N) is not None and b-g(Z-1,N)<0: ex.append('p')
    cnt[len(ex)]=cnt.get(len(ex),0)+1
    if not ex: noexit.append((Z,N))
    if ex==['a']: alpha_only.append((Z,N,a+BA-b))
P("| exits open | nuclides |"); P("|---|---|")
for k in sorted(cnt,key=str): P(f"| {k} | {cnt[k]} |")
P(f"\n**No exit open: {len(noexit)} nuclides.** By mass number: {sum(1 for Z,N in noexit if Z+N<=60)} up to A = 60, {sum(1 for Z,N in noexit if 60<Z+N<=140)} from 61 to 140, {sum(1 for Z,N in noexit if Z+N>140)} above 140.\n")
P("Heaviest with no exit: "+", ".join(nm(Z,N) for Z,N in sorted(noexit,key=lambda t:-(t[0]+t[1]))[:8])+".\n")
P(f"**Alpha is the only exit open: {len(alpha_only)} nuclides.** These are beta-stable but could shed an alpha on energy alone. The lightest: "+", ".join(f"{nm(Z,N)} ({q:.2f} MeV)" for Z,N,q in sorted(alpha_only,key=lambda t:t[0]+t[1])[:12])+".\n")
P("Even-odd make-up of the no-exit set:\n"); P("| Z | N | nuclides |"); P("|---|---|---|")
for pz,pn_ in ((0,0),(0,1),(1,0),(1,1)):
    s=[(Z,N) for Z,N in noexit if Z%2==pz and N%2==pn_]
    P(f"| {'even' if not pz else 'odd'} | {'even' if not pn_ else 'odd'} | {len(s)}"+(f" ({', '.join(nm(Z,N) for Z,N in s)})" if len(s)<=8 else "")+" |")
# ---------- 7. freedoms
P("\n## 7. Freedoms removed\n")
P("Note: 3n − 6 is 0, 3, 6 for n = 2, 3, 4. It is NOT 1 for two bodies. Two alphas have no freedom to remove on this count, and Be-8 has no leftover binding.\n")
P("3n − 6 for n alphas, against the binding left over after the alphas' own (BE − n·BE(⁴He)), per freedom.\n"); P("| nuclide | alphas n | 3n − 6 | leftover binding (MeV) | per freedom (MeV) |"); P("|---|---|---|---|---|")
for n in range(2,16):
    b=g(2*n,2*n)
    if b: r=b-n*BA; P(f"| {nm(2*n,2*n)} | {n} | {3*n-6} | {r:.2f} | {(r/(3*n-6) if n>2 else float('nan')):.2f} |")
open(os.path.join(HERE,'..','..','review','2026-11-18','ATLAS-slices.md'),'w').write("\n".join(L)+"\n"); print(len(L),'lines written')
