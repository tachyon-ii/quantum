"""ruler/euler_ruler.py — the 'Euler ruler' put to the test (James, 23 Nov 2026): if nature is measured with the right
(irrational) ruler, do its numbers come out whole?  Three operational readings, each with a chance control, because a dense
enough ruler fits anything (the 6*pi^5 lesson). Seeds fixed. Nothing is fitted and kept; every test reports a p-value against
surrogates built to have NO structure.

 T1  SCALES pi, e, phi.  Is a pure number x = (p/q) * pi^a * e^b * phi^c  (p,q<=10; a,b,c in -5..5) ?
     For each stubborn constant: best relative miss, and how often a RANDOM number of the same size is fitted at least as well.
     Sub-rulers (pi only; e only; phi only; pi and e) reported too. Combined verdict by Fisher's method.
 T2  COMMON MEASURE.  Is there a unit in which a set of energies are whole numbers?  Statistic: mean distance to the nearest
     whole number at the best unit (units scanned so the median lies between 1 and 8). Control: sets of the same size and
     spread with no common measure. Positive control: Dalton's nitrogen oxides (must be detected).
     Sets: alpha gains on the N=Z ladder; alpha gains over the whole chart; nucleon-rung contact energies; odd-even gaps.
 T3  SMALL-RATIO LOCKS.  Are ratios between a nucleus's lowest levels nearer to simple fractions (denominator <= 4) than chance?
     Level energies FROM MEMORY (flagged). Positive control: a rigid rotor and a pure vibrator.
 T4  ONE STEP BETWEEN LEVELS.  Is the sequence of closed numbers evenly spaced on a logarithmic scale (a fixed ratio per level)?

Sources: CODATA 2018/2022 and PDG values typed from memory (flagged, to be checked); AME2020 via kernel/data.py.
Grace (Claude Fable 5.2), 23 Nov 2026."""
