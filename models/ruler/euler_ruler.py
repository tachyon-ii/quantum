def stat(x):
    x=np.asarray(x,float); med=np.median(x); us=med/np.linspace(1,8,1401); r=x[None,:]/us[:,None]; s=np.abs(r-np.round(r)).mean(1); i=s.argmin(); return s[i],us[i]
def ptest(x,n=4000):
    x=np.asarray(x,float); s0,u0=stat(x); lo,hi=x.min(),x.max(); cnt=0
    for _ in range(n):
        cnt+= stat(rng.uniform(lo,hi,len(x)))[0]<=s0
    return s0,u0,(cnt+1)/(n+1)
