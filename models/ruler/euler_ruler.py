# high-resolution p for the two pi-only hits, and a combination over constants that are independent of one another
arr,vals=fam['π only']; pr("**The two hits on the π-only ruler, with 400,000 surrogates each:**\n"); pr("| constant | expression | miss | p (single) | after allowing for the 70 constant-ruler pairs tried here |"); pr("|---|---|---|---|---|")
for cn in ('proton/electron mass','proton magnetic moment (nuclear magnetons)'):
    x=CONST[cn]; d,j=best(np.log(x),arr); v=vals[j]; sur=np.log(x)+rng.uniform(-np.log(2),np.log(2),400000)
    i=np.clip(np.searchsorted(arr,sur),1,len(arr)-1); ds=np.minimum(np.abs(arr[i]-sur),np.abs(arr[i-1]-sur)); p=(np.sum(ds<=d)+1)/(len(ds)+1)
    pr(f"| {cn} | ({v[4]}/{v[5]})·π^{v[1]} | {d:.1e} | {p:.1e} | {min(1,1-(1-p)**70):.3f} |")
indep=['1/alpha (137.036)','proton/electron mass','muon/electron mass','tau/electron mass','(neutron-proton)/electron','proton magnetic moment (nuclear magnetons)','neutron magnetic moment, size','electron anomaly a_e','weak mixing sin^2 (Z pole)','Higgs/Z mass']
idx=[list(CONST).index(c) for c in indep]
