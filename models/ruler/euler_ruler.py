for nm,_ in RUL:
    p=np.array(P[nm]); F=-2*np.log(p).sum(); pr(f"| {nm} | {len(fam[nm][0])} | {chi2.sf(F,2*len(p)):.2f} | {kstest(p,'uniform').pvalue:.2f} | {p.min():.3f} |")
arr,vals=fam['π only']; d,j=best(np.log(1836.15267343),arr); v=vals[j]
