fr=sorted({(p,q) for p in range(1,11) for q in range(1,11) if math.gcd(p,q)==1})
def family(use):
    ex=range(-5,6); vals=[]
    for a in (ex if 'pi' in use else [0]):
        for b in (ex if 'e' in use else [0]):
            for c in (ex if 'phi' in use else [0]):
                base=a*np.log(PI)+b*np.log(E)+c*np.log(PHI)
                for p,q in fr: vals.append((base+np.log(p/q),a,b,c,p,q))
    vals.sort(); return np.array([v[0] for v in vals]),vals
def best(logx,arr):
    i=np.searchsorted(arr,logx); c=[j for j in (i-1,i) if 0<=j<len(arr)]; j=min(c,key=lambda j:abs(arr[j]-logx)); return abs(arr[j]-logx),j
pr("## T1. The three scales π, e, φ against the stubborn pure numbers\n")
pr("Ruler: x = (p/q)·π^a·e^b·φ^c, with p, q ≤ 10 and a, b, c from −5 to 5. Control: 4,000 random numbers within a factor of two of each constant.\n")
RUL=[('π, e, φ',('pi','e','phi')),('π and e',('pi','e')),('π only',('pi',)),('e only',('e',)),('φ only',('phi',))]
fam={nm:family(u) for nm,u in RUL}
pr("| constant | "+" | ".join(f"{nm}: best miss, p" for nm,_ in RUL)+" | best expression on the full ruler |"); pr("|---|"+"---|"*(len(RUL)+1))
P={nm:[] for nm,_ in RUL}
for cn,x in CONST.items():
    row=f"| {cn} |"
    for nm,_ in RUL:
        arr,vals=fam[nm]; d,j=best(np.log(x),arr)
        sur=np.log(x)+rng.uniform(-np.log(2),np.log(2),4000); ds=np.array([best(s,arr)[0] for s in sur]); p=(np.sum(ds<=d)+1)/(len(ds)+1); P[nm].append(p)
        row+=f" {d:.1e}, p={p:.2f} |"
        if nm=='π, e, φ': v=vals[j]; expr=f"({v[4]}/{v[5]})·π^{v[1]}·e^{v[2]}·φ^{v[3]}"
    pr(row+f" {expr} |")
from scipy.stats import chi2,kstest
